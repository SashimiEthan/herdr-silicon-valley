def icon_svg(name, art, square=11):
    """`art` as an SVG mask, a rect per run of ink. `square`: the side every row and
    column must have, or None for a mark of its own size."""
    w, h = len(art[0]), len(art)
    assert all(len(r) == w and set(r) <= set("#.") for r in art), name
    assert square is None or (w, h) == (square, square), name
    rects = []
    for y, row in enumerate(art):
        x = 0
        while x < w:
            if row[x] != "#":
                x += 1
                continue
            start = x
            while x < w and row[x] == "#":
                x += 1
            rects.append(f'<rect x="{start}" y="{y}" width="{x - start}" height="1"/>')
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{w * 4}" height="{h * 4}" viewBox="0 0 {w} {h}" '
            'fill="currentColor" shape-rendering="crispEdges">' + "".join(rects) + "</svg>\n")
